    function normalize(x) {
        const base = String(x || "").toLowerCase().split(/[-_]/)[0];
        return LANGS.includes(base) ? base : null;
    }
    function detect() {
        try {
            const saved = normalize(localStorage.getItem(STORE_KEY));
            if (saved) return saved;
        } catch (e) {
            /* storage unavailable */
        }
        const list = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]) || [];
        for (const l of list) {
            const n = normalize(l);
            if (n) return n;
        }
        return "en";
    }

    let lang = detect();

    function lookup(key) {
        const v = T[lang] && T[lang][key];
        return v != null ? v : T.en[key] != null ? T.en[key] : key;
    }
    function fill(s, p) {
        return p ? s.replace(/\{(\w+)\}/g, (m, k) => (k in p ? String(p[k]) : m)) : s;
    }
    /** Translated string with {placeholders} filled. */
    function t(key, params) {
        return fill(lookup(key), params);
    }
    /** Count-aware: picks key_one / key_other (falling back to key_other, then key). */
    function pluralKey(key, n) {
        const want = key + (n === 1 ? "_one" : "_other");
        const mine = T[lang] || {};
        if (mine[want] != null) return want;
        if (mine[key + "_other"] != null) return key + "_other";
        return T.en[want] != null ? want : key;
    }
    function tn(key, n, params) {
        return t(pluralKey(key, n), Object.assign({ n }, params));
    }
    /**
     * Like t(), but params may be DOM nodes: returns an array of strings and
     * nodes for h() to append, so a translated sentence can hold a name tag.
     */
    function tx(key, params) {
        const out = [];
        const s = lookup(key);
        let last = 0;
        s.replace(/\{(\w+)\}/g, (m, k, at) => {
            if (at > last) out.push(s.slice(last, at));
            out.push(params && k in params ? params[k] : m);
            last = at + m.length;
            return m;
        });
        if (last < s.length) out.push(s.slice(last));
        return out;
    }
    function setLang(l) {
        const n = normalize(l);
        if (!n || n === lang) return false;
        lang = n;
        try {
            localStorage.setItem(STORE_KEY, n);
        } catch (e) {
            /* storage unavailable: the choice lasts for this session */
        }
        return true;
    }

    return {
        LANGS,
        SHORT,
        NAMES,
        t,
        tn,
        tx,
        setLang,
        get lang() {
            return lang;
        },
    };
